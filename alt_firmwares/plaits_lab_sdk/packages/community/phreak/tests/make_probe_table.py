"""Writes src/phreak_probe_table.h, one cycle of the V.34 line probe.

Every probe tone is a multiple of the base, so the sum is periodic in the base
phase and one cycle, indexed by that phase, plays it at any pitch. Summing the
21 sines per sample instead cost about twice the CPU budget.

    python3 tests/make_probe_table.py
"""

import math
from pathlib import Path

PROBE = (150, 3750, 900, 1200)  # base, top, skipped, skipped (and their doubles)
PHASE = 0.37                    # tone k starts at PHASE * k * k cycles
GAIN = 0.05                     # the 21-tone sum peaks at about 8.8
SIZE = 512

HEADER = Path(__file__).resolve().parents[1] / "src" / "phreak_probe_table.h"


def multiples():
    base, top, skip_a, skip_b = PROBE
    skipped = {skip_a, skip_b, 2 * skip_a, 2 * skip_b}
    return [k for k in range(1, top // base + 1) if k * base not in skipped]


def cycle():
    ks = multiples()
    return [sum(math.sin(2 * math.pi * (k * i / SIZE + PHASE * k * k)) for k in ks)
            for i in range(SIZE)]


def header():
    values = cycle()
    peak = max(abs(v) for v in values)
    table = [round(v / peak * 32767) for v in values]
    table.append(table[0])
    rows = [", ".join(str(v) for v in table[i:i + 12]) for i in range(0, len(table), 12)]
    body = ",\n  ".join(rows)
    return f"""// Copyright 2026 Matt Policastro.
// SPDX-License-Identifier: MIT
//
// Generated by tests/make_probe_table.py; do not edit.
//
// One cycle of the V.34 line probe ({len(multiples())} tones), {SIZE} points plus a
// guard point repeating the first, as int16. kProbeScale restores the probe's
// level ({GAIN} times the sum of unit sines).

#ifndef PLAITS_LAB_PHREAK_PROBE_TABLE_H_
#define PLAITS_LAB_PHREAK_PROBE_TABLE_H_

#include "stmlib/stmlib.h"

namespace plaits {{
namespace phreak {{

const size_t kProbeTableSize = {SIZE};
const float kProbeScale = {GAIN * peak / 32767:.9e}f;

const int16_t kProbeTable[kProbeTableSize + 1] = {{
  {body}
}};

}}  // namespace phreak
}}  // namespace plaits

#endif  // PLAITS_LAB_PHREAK_PROBE_TABLE_H_
"""


if __name__ == "__main__":
    HEADER.write_text(header(), encoding="utf-8")
